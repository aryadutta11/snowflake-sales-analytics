CREATE OR REPLACE VIEW SUPERSTORE_DB.ANALYTICS.V_SALES_ANALYTICS AS
SELECT
    ROW_ID,
    ORDER_ID,
    ORDER_DATE,
    SHIP_DATE,
    SHIPPING_DAYS,
    SHIP_MODE,
    CUSTOMER_ID,
    CUSTOMER_NAME,
    SEGMENT,
    COUNTRY,
    CITY,
    STATE,
    POSTAL_CODE,
    REGION,
    PRODUCT_ID,
    CATEGORY,
    SUB_CATEGORY,
    PRODUCT_NAME,
    SALES,
    YEAR(ORDER_DATE) AS ORDER_YEAR,
    MONTH(ORDER_DATE) AS ORDER_MONTH,
    MONTHNAME(ORDER_DATE) AS ORDER_MONTH_NAME,
    QUARTER(ORDER_DATE) AS ORDER_QUARTER
FROM SUPERSTORE_DB.CLEAN.SUPERSTORE;